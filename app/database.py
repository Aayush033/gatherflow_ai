import sqlite3
from pathlib import Path
from contextlib import contextmanager
from app.config import settings

def get_db_path() -> Path:
    db_url = settings.DATABASE_URL
    if db_url and db_url.startswith("sqlite:///"):
        path_part = db_url[len("sqlite:///"):]
        return Path(path_part)
    return settings.DATABASE_PATH

def init_db(db_path: Path | None = None):
    """Initializes the SQLite database with full schema and WAL mode."""
    target_path = db_path or get_db_path()
    target_path.parent.mkdir(parents=True, exist_ok=True)
    
    with sqlite3.connect(target_path) as conn:
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA foreign_keys=ON;")
        cursor = conn.cursor()
        
        # 1. Users table (Supports isolation by session token or user_id)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id TEXT PRIMARY KEY,
            email TEXT UNIQUE,
            name TEXT,
            session_token TEXT UNIQUE NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
        """)
        
        # 2. Events table
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS events (
            id TEXT PRIMARY KEY,
            user_id TEXT NOT NULL,
            title TEXT NOT NULL,
            event_type TEXT NOT NULL, -- wedding, birthday, community, custom
            date TEXT NOT NULL,
            time_details TEXT,
            location TEXT NOT NULL,
            venue_preferences TEXT,
            guest_count INTEGER NOT NULL,
            budget REAL NOT NULL,
            currency TEXT NOT NULL DEFAULT 'INR',
            theme TEXT,
            cultural_preferences TEXT,
            dietary_accessibility TEXT,
            priorities_constraints TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        );
        """)
        
        # 3. Event Plans (Generated by AI and user-editable)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS event_plans (
            id TEXT PRIMARY KEY,
            event_id TEXT UNIQUE NOT NULL,
            concept TEXT,
            theme_details TEXT,
            budget_allocation_json TEXT,
            timeline_milestones_json TEXT,
            checklist_json TEXT,
            vendor_categories_json TEXT,
            risks_json TEXT,
            contingencies_json TEXT,
            next_actions_json TEXT,
            raw_ai_response TEXT,
            is_ai_generated INTEGER DEFAULT 1,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
        );
        """)
        
        # 4. Budget Items (Distinct estimates, quotes, commitments, actuals)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS budget_items (
            id TEXT PRIMARY KEY,
            event_id TEXT NOT NULL,
            category TEXT NOT NULL,
            item_name TEXT NOT NULL,
            estimated_amount REAL NOT NULL DEFAULT 0.0,
            quoted_amount REAL NOT NULL DEFAULT 0.0,
            committed_amount REAL NOT NULL DEFAULT 0.0,
            actual_amount REAL NOT NULL DEFAULT 0.0,
            status TEXT NOT NULL DEFAULT 'planned', -- planned, quoted, committed, paid
            notes TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
        );
        """)
        
        # 5. Tasks table
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS tasks (
            id TEXT PRIMARY KEY,
            event_id TEXT NOT NULL,
            title TEXT NOT NULL,
            description TEXT,
            category TEXT NOT NULL DEFAULT 'General',
            due_date TEXT,
            priority TEXT NOT NULL DEFAULT 'medium', -- low, medium, high, critical
            status TEXT NOT NULL DEFAULT 'todo', -- todo, in_progress, completed
            assignee TEXT,
            dependency_task_id TEXT,
            notes TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
            FOREIGN KEY (dependency_task_id) REFERENCES tasks(id) ON DELETE SET NULL
        );
        """)
        
        # 6. Vendors table
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS vendors (
            id TEXT PRIMARY KEY,
            event_id TEXT NOT NULL,
            name TEXT NOT NULL,
            category TEXT NOT NULL, -- Venue, Catering, Photography, Decoration, Entertainment, Invitations, Transport, Other
            contact_person TEXT,
            contact_phone TEXT,
            contact_email TEXT,
            quotation_amount REAL DEFAULT 0.0,
            status TEXT NOT NULL DEFAULT 'enquiry', -- enquiry, shortlisted, quoted, confirmed, rejected
            follow_up_date TEXT,
            notes TEXT,
            linked_budget_item_id TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
            FOREIGN KEY (linked_budget_item_id) REFERENCES budget_items(id) ON DELETE SET NULL
        );
        """)
        
        # 7. Plan Rescue Log (Audit trail of adaptive changes)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS plan_rescue_logs (
            id TEXT PRIMARY KEY,
            event_id TEXT NOT NULL,
            scenario_description TEXT NOT NULL,
            proposal_summary TEXT NOT NULL,
            full_proposal_json TEXT NOT NULL,
            applied INTEGER DEFAULT 0,
            applied_at TIMESTAMP,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
        );
        """)
        
        # 8. Copilot Conversations
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS copilot_messages (
            id TEXT PRIMARY KEY,
            event_id TEXT NOT NULL,
            role TEXT NOT NULL, -- user, assistant, system
            content TEXT NOT NULL,
            context_snapshot_json TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
        );
        """)
        
        # Indices for optimal efficiency and query speed
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_events_user ON events(user_id);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_budget_event ON budget_items(event_id);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_tasks_event ON tasks(event_id);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_vendors_event ON vendors(event_id);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_copilot_event ON copilot_messages(event_id);")
        
        conn.commit()
    
    # 9. Initialize ChromaDB vector database collections (vendors, knowledge, rescue)
    try:
        from app.vector_db import init_vector_db
        init_vector_db()
    except Exception as e:
        # Keep non-blocking if running in lightweight/isolated test environments
        pass

@contextmanager
def get_db(db_path: Path | None = None):
    """Context manager providing a SQLite connection with dict-like row factory and foreign keys."""
    target_path = db_path or get_db_path()
    conn = sqlite3.connect(target_path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON;")
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
